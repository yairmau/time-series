"""Bundle unchanged, regularly spaced excerpts of the course CSVs for offline use."""
import csv
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent


def number(value):
    try:
        result = float(value)
        return result if math.isfinite(result) else None
    except (ValueError, TypeError):
        return None


def load(name):
    with (HERE / name).open() as stream:
        return list(csv.DictReader(stream))


datasets = {}
for filename, time_column, minutes, selections in [
    ('cleaning1.csv', 'date', 5, [('A', 93600, 701), ('B', 600, 701), ('C', 55700, 701), ('D', 46000, 1501), ('E', 52300, 701)]),
    ('cleaning2_formated.csv', 'datetime', 60, [('A', 4000, 701), ('B', 7100, 701)]),
    ('cleaning3_formated.csv', 'time', 1440, [('A', 0, 365)]),
]:
    rows = load(filename)
    group = filename[len('cleaning')]
    for column, start, count in selections:
        excerpt = rows[start:start + count]
        key = f'challenge{group}{column}'
        datasets[key] = dict(label=f'Challenge data {group} · column {column}',
                             source=filename, column=column, offset=start, minutes=minutes,
                             start=excerpt[0][time_column].replace(' ', 'T'), unit='data units',
                             values=[number(row[column]) for row in excerpt])

rows = load('data_missing.csv')
temperature = dict(label='Temperature', source='data_missing.csv', minutes=120, unit='°C',
                   start=rows[0]['date'].replace(' ', 'T'),
                   **{key: [number(row[key]) for row in rows] for key in ['original', 'mis_1', 'mis_2', 'mis_3']})
payload = dict(challenges=datasets, temperature=temperature)
(HERE / 'lab' / 'data.js').write_text('// Generated by outliers/build-lab-data.py from the course CSV files.\n'
                                    + 'globalThis.OutlierData = ' + json.dumps(payload, separators=(',', ':'), allow_nan=False) + ';\n')
print(f'Bundled {len(datasets)} challenge excerpts and {len(rows)} temperature samples.')
