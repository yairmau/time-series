"""Regenerate the practice CSVs and browser data from the course's IMS records.

Run with Python + pandas from any directory. Keep one station: Jerusalem Centre,
2020–2022. The 2019 file is Givat Ram and is deliberately not concatenated.
Timestamps are local standard time (the source files' winter clock), with no DST
conversion. No interpolation; incomplete bins would remain missing.
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
frames = []
for year, filename in [(2020, "jerusalem_2020_10min.csv"),
                       (2021, "jerusalem_2021.csv"), (2022, "jerusalem_2022.csv")]:
    frame = pd.read_csv(HERE.parent / "archive/data" / filename, low_memory=False)
    # English and Hebrew files place time and temperature at the same positions.
    dates = pd.to_datetime(frame.iloc[:, 1], dayfirst=True)
    values = pd.to_numeric(frame.iloc[:, 4], errors="coerce")
    series = pd.Series(values.to_numpy(), index=dates).sort_index()
    assert not series.index.duplicated().any()
    frames.append(series)

temperature = pd.concat(frames).sort_index()
daily = temperature.resample("D").agg(["mean", "count"])
hourly = temperature.loc["2022-07"].resample("h").agg(["mean", "count"])
datasets = {}
for key, table, minimum, minutes, filename, label in [
    ("daily", daily, 115, 1440, "jerusalem_daily_2020_2022.csv", "Jerusalem · daily means · 2020–2022"),
    ("hourly", hourly, 4, 60, "jerusalem_hourly_july_2022.csv", "Jerusalem · hourly means · July 2022"),
]:
    values = table["mean"].where(table["count"] >= minimum).round(6)
    assert values.notna().all(), "New source gaps need review before regenerating this lesson"
    output = pd.DataFrame({"temperature": values, "observations": table["count"]})
    output.index.name = "time"
    output.to_csv(HERE / "practice-data" / filename)
    datasets[key] = dict(label=label, start=values.index[0].isoformat(), minutes=minutes,
                         values=values.tolist(), file=filename, unit="°C")

(HERE / "practice-lab/data.js").write_text(
    "// Generated by stationarity/build-practice-data.py; do not hand-edit.\n"
    "globalThis.StationarityData = " + json.dumps(datasets, separators=(",", ":"), allow_nan=False) + ";\n")
print("Generated", {key: len(data["values"]) for key, data in datasets.items()})

# A separate resource name avoids Quarto rewriting a chapter-source link to HTML.
# Student download stays small and starts with no saved output.
notebook = json.loads((HERE / "practice_ARIMA.ipynb").read_text())
for cell in notebook["cells"]:
    if cell["cell_type"] == "code":
        cell["outputs"] = []
        cell["execution_count"] = None
        cell.get("metadata", {}).pop("execution", None)
(HERE / "practice-data/stationarity-practice.ipynb").write_text(json.dumps(notebook, indent=1) + "\n")
